const dictionaries: Record<Language, Dictionary> = { zh, en };

export function detectLanguage(locale?: string): Language {
  const value = (
    locale ??
    (typeof navigator !== 'undefined' ? navigator.languages?.[0] ?? navigator.language : '')
  ).toLowerCase();
  return value.startsWith('zh') ? 'zh' : 'en';
}

export function t(language: Language, key: string, values?: Record<string, string | number>): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function rangeLabel(language: Language, preset: RangePreset): string {
  return t(language, `range.${preset}`);
}



